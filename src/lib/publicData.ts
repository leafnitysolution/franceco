function serialize<T>(data: T): T {
  return JSON.parse(JSON.stringify(data));
}

export async function getPublicRoutes(): Promise<any[]> {
  try {
    await ensureLocationsSeeded();
    const routes = await db.route.findMany({
      where: { isActive: true },
      include: {
        origin: true,
        destination: true,
      },
      orderBy: { slug: 'asc' },
    });
    if (routes && routes.length > 0) {
      return serialize(routes);
    }
  } catch (err) {
    console.warn('Database query failed for getPublicRoutes, using fallback:', err);
  }
  return serialize(DEFAULT_ROUTES);
}

export async function getPublicLocations(): Promise<any[]> {
  try {
    const locations = await db.location.findMany({
      orderBy: { name: 'asc' },
    });
    if (locations && locations.length > 0) {
      return serialize(locations);
    }
  } catch (err) {
    console.warn('Database query failed for getPublicLocations, using fallback:', err);
  }
  return serialize(DEFAULT_LOCATIONS);
}

export async function getPublicCategories(): Promise<any[]> {
  try {
    const categories = await db.locationCategory.findMany({
      orderBy: [{ sortOrder: 'asc' }, { name: 'asc' }],
    });
    if (categories && categories.length > 0) {
      return serialize(categories);
    }
  } catch (err) {
    console.warn('Database query failed for getPublicCategories, using fallback:', err);
  }
  return serialize(DEFAULT_CATEGORIES);
}
